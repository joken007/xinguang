/**
 * 跨会话去重的语录抽取器（localStorage 持久化）。
 * 规则：优先给出尚未展示过的语录；池子见底时重置记录、开启新一轮洗牌，
 * 保证"每次重新开始都不重复直到全部看完一遍"，同时新一轮第一条不与上轮末条重复。
 * localStorage 不可用（隐私模式等）时自动降级为仅会话内去重。
 */
export class QuoteDeck {
  static _storageKey = 'xinguang_shown_quotes';

  constructor(list = QUOTES) {
    this.list = list.slice();
    this.seen = QuoteDeck._loadSeen();
    this.order = [];
    this.cursor = 0;
    this._reshuffle();
  }

  static _loadSeen() {
    try {
      const raw = localStorage.getItem(QuoteDeck._storageKey);
      if (!raw) return [];
      const arr = JSON.parse(raw);
      if (!Array.isArray(arr)) return [];
      const available = new Set(QUOTE_KEYS());
      return arr.filter(t => available.has(t));
    } catch (e) {
      return [];
    }
  }

  static _saveSeen(seen) {
    try {
      localStorage.setItem(QuoteDeck._storageKey, JSON.stringify(seen));
    } catch (e) {
      /* 隐私模式下 localStorage 不可用，静默降级 */
    }
  }

  _reshuffle() {
    // 待抽取池：所有语录中去掉已展示过的
    let pool = this.list.filter(q => !this.seen.includes(q.text));
    if (pool.length === 0) {
      // 全部看过一遍：重置记录，开启新一轮
      this.seen = [];
      QuoteDeck._saveSeen(this.seen);
      pool = this.list.slice();
    }
    // 洗牌后若第一条与最近一条重复且还有别的选择，则换开
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    if (this.last && pool.length > 1 && pool[0].text === this.last) {
      const k = 1 + Math.floor(Math.random() * (pool.length - 1));
      [pool[0], pool[k]] = [pool[k], pool[0]];
    }
    this.order = pool;
    this.cursor = 0;
  }

  next() {
    if (this.cursor >= this.order.length) this._reshuffle();
    const item = this.order[this.cursor++];
    this.seen.push(item.text);
    QuoteDeck._saveSeen(this.seen);
    this.last = item.text;
    return item;
  }
}

/** 收集所有语录文本作为去重键集合（刷新/重启时清除无效历史记录用） */
function QUOTE_KEYS() {
  return new Set(QUOTES.map(q => q.text));
}
